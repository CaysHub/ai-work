-- 机器人模块新建四表，包含 2026-11-19 止的接管结构。

CREATE TABLE IF NOT EXISTS sw_im_bot (
 parent_bot_id BIGINT DEFAULT NULL COMMENT '人员接管配置所属的原机器人主键',
 KEY idx_im_bot_parent (parent_bot_id),
 identity_mode VARCHAR(16) NOT NULL DEFAULT 'BOT' COMMENT '收发身份：BOT机器人，USER授权真人',
 takeover_config_cipher MEDIUMTEXT DEFAULT NULL COMMENT '统一主密钥加密的真人接管配置、用户授权令牌及会话发现进度，仅后端读取',
 id BIGINT NOT NULL PRIMARY KEY COMMENT '记录主键',
 tenant_id VARCHAR(64) NOT NULL COMMENT '归属工作台租户标识',
 platform VARCHAR(16) NOT NULL COMMENT '平台代码：WECOM 企业微信，FEISHU 飞书，DINGTALK 钉钉',
 external_app_id VARCHAR(128) NOT NULL COMMENT '平台应用标识：企业微信 BotID 、飞书 AppID 或钉钉应用标识',
 app_id_key CHAR(64) NOT NULL COMMENT '平台应用标识的大小写敏感摘要，用于唯一约束',
 secret_cipher TEXT NOT NULL COMMENT '使用项目统一主密钥加密的平台密钥',
 document_config_cipher TEXT DEFAULT NULL COMMENT '统一主密钥加密的企微七类MCP授权配置，兼容旧文档地址，仅后端读取',
 name VARCHAR(128) NOT NULL COMMENT '机器人或目标会话显示名称',
 description VARCHAR(1000) DEFAULT NULL COMMENT '机器人用途说明',
 enabled TINYINT NOT NULL DEFAULT 0 COMMENT '机器人是否启用，0 否、1 是',
 auto_process_enabled TINYINT NOT NULL DEFAULT 0 COMMENT '是否自动处理普通文本消息，0 否、1 是',
 group_enabled TINYINT NOT NULL DEFAULT 0 COMMENT '是否启用群聊处理，默认关闭，0 否、1 是',
 allowed_group_chat_ids TEXT COMMENT '允许处理消息的外部群会话标识列表，以 JSON 数组保存',
 config_version BIGINT NOT NULL DEFAULT 1 COMMENT '管理配置版本，用于防止并发覆盖',
 owner_node VARCHAR(128) DEFAULT NULL COMMENT '持有当前机器人连接的后端节点标识',
 lease_until DATETIME(6) DEFAULT NULL COMMENT '节点归属租约截止时间，使用数据库时间',
 owner_version BIGINT NOT NULL DEFAULT 0 COMMENT '节点归属代次，接管时递增以拒绝旧节点写入',
 connection_state VARCHAR(16) NOT NULL DEFAULT 'DISABLED' COMMENT '连接状态：停用、连接中、在线或错误',
 last_heartbeat_at DATETIME(6) DEFAULT NULL COMMENT '后端最近一次登记连接状态的时间',
 last_error VARCHAR(1000) DEFAULT NULL COMMENT '供页面展示的脱敏错误说明',
 create_user_id VARCHAR(64) NOT NULL COMMENT '创建记录的工作台用户标识',
 update_user_id VARCHAR(64) NOT NULL COMMENT '最近修改记录的工作台用户标识',
 create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '数据库记录创建时间',
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '数据库记录最近更新时间',
 UNIQUE KEY uk_im_bot_app (platform,app_id_key),
 KEY idx_im_bot_tenant (tenant_id,enabled),
 KEY idx_im_bot_lease (lease_until)
) ENGINE=InnoDB COMMENT='企业消息机器人配置及运行归属';

CREATE TABLE IF NOT EXISTS sw_im_bot_user (
 id BIGINT NOT NULL PRIMARY KEY COMMENT '记录主键',
 bot_id BIGINT NOT NULL COMMENT '机器人配置主键',
 tenant_id VARCHAR(64) NOT NULL COMMENT '归属工作台租户标识',
 user_id VARCHAR(64) NOT NULL COMMENT '归属工作台用户标识',
 user_name VARCHAR(128) DEFAULT NULL COMMENT '工作台用户显示名称',
 authorized TINYINT NOT NULL DEFAULT 1 COMMENT '是否已被管理员授予机器人使用权，0 否、1 是',
 external_user_id VARCHAR(256) DEFAULT NULL COMMENT '当前机器人下的外部用户标识',
 external_user_key CHAR(64) DEFAULT NULL COMMENT '外部用户标识的大小写敏感摘要',
 binding_code_hash CHAR(64) DEFAULT NULL COMMENT '一次性绑定码摘要，不保存原始绑定码',
 binding_code_expires_at DATETIME(6) DEFAULT NULL COMMENT '一次性绑定码截止时间',
 bound_at DATETIME(6) DEFAULT NULL COMMENT '外部身份绑定成功时间',
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '数据库记录最近更新时间',
 UNIQUE KEY uk_im_bot_user (bot_id,user_id),
 UNIQUE KEY uk_im_bot_external_user (bot_id,external_user_key),
 UNIQUE KEY uk_im_bot_binding_code (bot_id,binding_code_hash),
 KEY idx_im_bot_user_scope (tenant_id,user_id,authorized)
) ENGINE=InnoDB COMMENT='机器人用户授权及外部身份绑定';

CREATE TABLE IF NOT EXISTS sw_im_bot_session (
 takeover_state MEDIUMTEXT DEFAULT NULL COMMENT '真人会话读取水位、固定分页窗口及待合并消息，仅后端读取',
 id BIGINT NOT NULL PRIMARY KEY COMMENT '记录主键',
 bot_id BIGINT NOT NULL COMMENT '机器人配置主键',
 tenant_id VARCHAR(64) NOT NULL COMMENT '归属工作台租户标识',
 user_id VARCHAR(64) NOT NULL COMMENT '归属工作台用户标识',
 external_chat_id VARCHAR(256) NOT NULL COMMENT '平台外部会话标识',
 chat_key CHAR(64) NOT NULL COMMENT '平台会话标识的大小写敏感摘要',
 session_type VARCHAR(16) NOT NULL COMMENT '会话类型：P2P 单聊，GROUP 群聊',
 name VARCHAR(128) DEFAULT NULL COMMENT '机器人或目标会话显示名称',
 session_id VARCHAR(128) DEFAULT NULL COMMENT '关联的工作台会话标识',
 last_interaction_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '最近一次观察到有效用户互动的时间',
 UNIQUE KEY uk_im_bot_session (bot_id,user_id,chat_key),
 KEY idx_im_bot_session_scope (tenant_id,user_id,bot_id,last_interaction_at)
) ENGINE=InnoDB COMMENT='机器人外部会话与工作台会话映射';

CREATE TABLE IF NOT EXISTS sw_im_bot_message (
 id BIGINT NOT NULL PRIMARY KEY COMMENT '记录主键',
 bot_id BIGINT NOT NULL COMMENT '机器人配置主键',
 tenant_id VARCHAR(64) NOT NULL COMMENT '归属工作台租户标识',
 user_id VARCHAR(64) NOT NULL COMMENT '归属工作台用户标识',
 target_session_id BIGINT NOT NULL COMMENT '本次消息对应的后端目标会话主键',
 direction VARCHAR(16) NOT NULL COMMENT '消息方向：INBOUND 入站，OUTBOUND 主动发送',
 content_type VARCHAR(16) NOT NULL COMMENT '内容类型：TEXT文本、MARKDOWN正文、FILE文档',
 file_id BIGINT DEFAULT NULL COMMENT '已保存的输入文档或待发送成果文件主键，关联sw_file.id',
 content MEDIUMTEXT COMMENT '消息正文；绑定控制消息不包含原始绑定码',
 reply_content MEDIUMTEXT COMMENT '从原工作台会话提取的最终回复正文',
 inbound_key CHAR(64) DEFAULT NULL COMMENT '平台入站消息标识的摘要，用于消息去重',
 external_message_id VARCHAR(256) DEFAULT NULL COMMENT '平台原始入站消息标识',
 reply_context TEXT COMMENT '平台回复所需的连接标识与请求上下文，仅后端使用',
 provider_uuid VARCHAR(50) DEFAULT NULL COMMENT '固定的平台发送请求标识，用于平台防重',
 provider_message_id VARCHAR(256) DEFAULT NULL COMMENT '平台确认受理后返回的消息标识',
 request_id VARCHAR(128) DEFAULT NULL COMMENT '一次逻辑请求的稳定标识，重试时复用',
 request_hash CHAR(64) DEFAULT NULL COMMENT '主动发送的目标和正文摘要，用于检测幂等冲突',
 process_state VARCHAR(24) DEFAULT NULL COMMENT '业务处理状态，与平台发送状态分别维护',
 send_state VARCHAR(16) DEFAULT NULL COMMENT '平台发送状态，不代表对方已读',
 session_id VARCHAR(128) DEFAULT NULL COMMENT '关联的工作台会话标识',
 db_message_id BIGINT DEFAULT NULL COMMENT '原工作台会话实际受理的消息主键',
 run_id VARCHAR(128) DEFAULT NULL COMMENT '原工作台会话实际受理的运行标识',
 last_seq INT NOT NULL DEFAULT 0 COMMENT '已观察的原会话事件序号',
 last_error VARCHAR(1000) DEFAULT NULL COMMENT '供页面展示的脱敏错误说明',
 processing_owner_version BIGINT DEFAULT NULL COMMENT '最近处理该消息的机器人归属代次',
 expires_at DATETIME(6) DEFAULT NULL COMMENT '待发送消息的截止时间',
 create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '数据库记录创建时间',
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '数据库记录最近更新时间',
 UNIQUE KEY uk_im_bot_inbound (bot_id,inbound_key),
 UNIQUE KEY uk_im_bot_send_request (tenant_id,user_id,bot_id,request_id),
 KEY idx_im_bot_process (bot_id,process_state,create_time),
 KEY idx_im_bot_send (bot_id,send_state,create_time),
 KEY idx_im_bot_message_scope (tenant_id,user_id,create_time),
 KEY idx_im_bot_message_session (target_session_id,process_state,create_time)
) ENGINE=InnoDB COMMENT='机器人消息处理结果及回复发送状态';
